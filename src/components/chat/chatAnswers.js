// ищем в сообщении слова из списков и возвращаем все подходящие ответы
export function findAnswers(text) {
    const message = text.toLowerCase();

    return [...otherAnswers, ...chatAnswers]
        .filter((item) => item.words.some((word) => message.includes(word)))
        .map((item) => item.answer);
}

